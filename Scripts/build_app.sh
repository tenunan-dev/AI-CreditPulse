#!/bin/zsh
# Builds AI CreditPulse.app from the SPM executable target.
# Usage: ./Scripts/build_app.sh [release|debug]
set -euo pipefail

CONFIG="${1:-release}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
APP_NAME="AI CreditPulse"
BUNDLE_ID="com.faisal.aicreditpulse"
BUILD_DIR="$ROOT/.build/spm-app"
APP_DIR="$BUILD_DIR/$APP_NAME.app"
CONTENTS="$APP_DIR/Contents"

# Prefer full Xcode when installed (SwiftUI macros live in the Xcode toolchain;
# the CommandLineTools toolchain lacks libSwiftUIMacros).
if [[ -d /Applications/Xcode.app/Contents/Developer ]]; then
  export DEVELOPER_DIR="/Applications/Xcode.app/Contents/Developer"
fi

# Build scratch OUTSIDE the iCloud-synced tree: files created under
# ~/Documents get fileprovider xattrs (fpfs#P/FinderInfo/provenance) that
# ad-hoc codesign refuses as "detritus" — this once blocked every build.
# A clean scratch directory keeps the merged resource bundle signable.
SWIFT_SCRATCH="${TMPDIR:-/tmp}/aicreditpulse-scratch"
mkdir -p "$SWIFT_SCRATCH"

cd "$ROOT"
swift build --scratch-path "$SWIFT_SCRATCH" -c "$CONFIG" 2>&1 || exit 1

BIN_DIR=".build/$(uname -m)-apple-macosx/$CONFIG"
[[ -x "$BIN_DIR/AICreditPulse" ]] || BIN_DIR="$SWIFT_SCRATCH/out/Products/$([ "$CONFIG" = release ] && echo Release || echo Debug)"
BIN="$BIN_DIR/AICreditPulse"
[[ -x "$BIN" ]] || BIN="$SWIFT_SCRATCH/out/Products/$([ "$CONFIG" = release ] && echo Release || echo Debug)/AICreditPulse"
[[ -x "$BIN" ]] || { echo "executable not found" >&2; exit 1; }

rm -rf "$APP_DIR"
mkdir -p "$CONTENTS/MacOS" "$CONTENTS/Resources"

cp "$BIN" "$CONTENTS/MacOS/$APP_NAME"

cat > "$CONTENTS/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleName</key><string>$APP_NAME</string>
    <key>CFBundleDisplayName</key><string>$APP_NAME</string>
    <key>CFBundleIdentifier</key><string>$BUNDLE_ID</string>
    <key>CFBundleVersion</key><string>0.1.0</string>
    <key>CFBundleShortVersionString</key><string>0.1.0</string>
    <key>CFBundlePackageType</key><string>APPL</string>
    <key>CFBundleExecutable</key><string>$APP_NAME</string>
    <key>CFBundleIconFile</key><string>AppIcon</string>
    <key>LSMinimumSystemVersion</key><string>14.0</string>
    <!-- Menu bar agent only: no Dock icon, no main window. -->
    <key>LSUIElement</key><true/>
    <key>NSHiDPIDeviceCapable</key><true/>
</dict>
</plist>
PLIST

# Minimal PkgInfo.
printf 'APPL????' > "$CONTENTS/PkgInfo"

# The Core library's SPM resource bundle is REQUIRED equipment: flags resolved
# via the manual bundle locator (MenubarIcon.resourcesBundle) live inside it.
# Copy the bundle whole, then also flatten its PNGs into Resources so a
# Bundle.main fallback can serve the icons if the bundle ever goes missing.
ICON_BUNDLE="$(find "$SWIFT_SCRATCH/out/Products" -name "AICreditPulse_AICreditPulseCore.bundle" 2>/dev/null | head -1)"
if [[ -n "$ICON_BUNDLE" ]]; then
  cp -R "$ICON_BUNDLE" "$CONTENTS/Resources/"
  ICON_BUNDLE_DIR="$ICON_BUNDLE/Contents/Resources/Resources"
  cp "$ICON_BUNDLE_DIR"/icon-*.png "$CONTENTS/Resources/" 2>/dev/null || true
fi
# Belt & braces: strip any sync-service metadata that could taint the
# bundle's signature; the icons must remain pixel-real (the smoke test's ink
# check is what guarantees they draw).
find "$CONTENTS" -name "._*" -delete 2>/dev/null || true
xattr -cr "$CONTENTS/Resources" 2>/dev/null || true
# The brand icon: Dock/Finder/About icon, generated by Scripts/make_icon.swift.
if [[ -f "$ROOT/Assets/AppIcon.icns" ]]; then
  cp "$ROOT/Assets/AppIcon.icns" "$CONTENTS/Resources/AppIcon.icns"
fi
ls "$CONTENTS/Resources/" 2>/dev/null

# Ad-hoc sign so macOS lets the bundle run its Process/security helpers cleanly.
codesign --force --deep --sign - "$APP_DIR" 2>/dev/null || true

echo "Built: $APP_DIR"
